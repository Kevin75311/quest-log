// Loads/saves the quest JSON files inside the personal-os checkout and renders a markdown view.
'use strict';
const fs = require('fs');
const path = require('path');
const R = require('../public/js/reducer.js');

const FILES = { missions: 'missions.json', player: 'player.json', events: 'events.json', inbox: 'inbox.json' };

function readJson(f, fallback) { try { return JSON.parse(fs.readFileSync(f, 'utf8')); } catch (e) { if (e.code === 'ENOENT') return fallback; throw new Error(`Cannot parse ${f}: ${e.message}`); } }
function writeAtomic(f, data) { const tmp = f + '.tmp-' + process.pid; fs.writeFileSync(tmp, data); fs.renameSync(tmp, f); }

class Store {
  constructor(dir, seedDir) { this.dir = dir; this.seedDir = seedDir; this.state = null; }
  ensure() {
    fs.mkdirSync(this.dir, { recursive: true });
    let seeded = false;
    for (const f of Object.values(FILES)) {
      const dst = path.join(this.dir, f);
      if (!fs.existsSync(dst)) { fs.copyFileSync(path.join(this.seedDir, f), dst); seeded = true; }
    }
    return seeded;
  }
  load() {
    const d = this.dir;
    const m = readJson(path.join(d, FILES.missions), { lines: [] });
    const p = readJson(path.join(d, FILES.player), { player: { xp: 0, streak: 0, history: [] }, focus: [] });
    const e = readJson(path.join(d, FILES.events), { events: [] });
    const i = readJson(path.join(d, FILES.inbox), { inbox: [] });
    this.state = { lines: m.lines || [], knownIds: m.knownIds || [], player: p.player || { xp: 0 }, focus: p.focus || [], events: e.events || [], inbox: i.inbox || [] };
    return this.state;
  }
  save(st, today) {
    const d = this.dir, j = o => JSON.stringify(o, null, 2) + '\n';
    writeAtomic(path.join(d, FILES.missions), j({ version: 1, lines: st.lines, knownIds: st.knownIds || [] }));
    writeAtomic(path.join(d, FILES.player), j({ version: 1, player: st.player, focus: st.focus }));
    writeAtomic(path.join(d, FILES.events), j({ version: 1, events: st.events }));
    writeAtomic(path.join(d, FILES.inbox), j({ version: 1, inbox: st.inbox }));
    writeAtomic(path.join(d, 'QUEST-LOG.md'), renderMarkdown(st, today));
    this.state = st;
  }
}

function renderMarkdown(st, today) {
  const L = [];
  const esc = s => String(s || '').replace(/\|/g, '\\|').replace(/\n/g, ' ');
  L.push('# Quest Log (generated)', '');
  L.push(`Generated by the Quest Log server on ${today}. **Do not edit this file by hand** — it is rebuilt from \`quest/*.json\` on every change.`);
  L.push('Agents: read this file for current mission-line status; propose changes through the Quest Log or edit the JSON with one writer at a time.', '');
  const p = st.player || {};
  L.push(`Level ${R.level(p.xp || 0)} · ${p.xp || 0} XP · streak ${p.streak || 0} day(s)`, '');
  L.push('## Today', '');
  if (!st.focus.length) L.push('_No quests picked for today._');
  st.focus.forEach(f => { const l = st.lines.find(x => x.id === f.line); const s = l && l.steps.find(x => x.id === f.step); if (s) L.push(`- [ ] ${s.id} — ${s.title} (${l.id} ${l.short})`); });
  L.push('');
  const urgent = [];
  st.lines.forEach(l => l.steps.forEach(s => { const u = R.urgency(s, today); if (u && u.level !== 'ok') urgent.push({ l, s, u }); }));
  urgent.sort((a, b) => a.u.days - b.u.days);
  L.push('## Deadlines within 7 days and check-ins', '');
  if (!urgent.length) L.push('_None._');
  urgent.forEach(({ l, s, u }) => L.push(`- ${u.level === 'late' ? `CHECK-IN (${u.kind} date ${u.date} passed)` : `${u.days} day(s) — ${u.kind} ${u.date}`}: ${s.id} ${s.title} (${l.id})`));
  L.push('');
  st.lines.forEach(l => {
    const done = l.steps.filter(s => s.status === 'done').length;
    L.push(`## ${l.id} · ${l.name} (${l.short}) — ${done}/${l.steps.length}, priority ${l.prio}`, '');
    if (l.blurb) L.push(l.blurb, '');
    if (l.boss) L.push(`Boss: **${l.boss.name}** — ${l.boss.date}${l.boss.note ? ` (${l.boss.note})` : ''}`, '');
    L.push('| # | ID | Step | Status | Priority | Planned | Due | Subtasks | Latest comment |', '| --- | --- | --- | --- | --- | --- | --- | --- | --- |');
    l.steps.forEach((s, i) => {
      const subs = s.subs || [], c = (s.comments || []).slice(-1)[0];
      L.push(`| ${i + 1} | ${s.id}${s.checkpoint ? ' (checkpoint)' : ''} | ${esc(s.title)} | ${s.status}${s.doneAt ? ' ' + s.doneAt.slice(0, 10) : ''} | ${s.priority} | ${s.planned || ''} | ${s.due || ''} | ${subs.length ? subs.filter(x => x.done).length + '/' + subs.length : ''} | ${c ? esc(c.text) + ' (' + c.at.slice(0, 10) + ')' : ''} |`);
    });
    L.push('');
  });
  if (st.inbox.length) { L.push('## Inbox (unsorted)', ''); st.inbox.forEach(x => L.push(`- ${x.t}`)); L.push(''); }
  const h = (p.history || []).slice(0, 20);
  if (h.length) { L.push('## Recent activity', ''); h.forEach(e => L.push(`- ${e.at.slice(0, 16).replace('T', ' ')} ${e.xp > 0 ? '+' : ''}${e.xp} XP — ${e.kind} ${e.step || ''} ${esc(e.title)}${e.comment ? ' — “' + esc(e.comment) + '”' : ''}`)); L.push(''); }
  return L.join('\n');
}

module.exports = { Store, renderMarkdown };
